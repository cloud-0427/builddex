package io.github.xjc.jiagu.local;

/** Stable diagnostic/audit codes, grouped by lifecycle then recovery/storage. Not funnel stages. */
public enum LocalStartupDiagnosticCode {
    APPLICATION_ATTACH_ENTER("APPLICATION_ATTACH_ENTER"),
    APPLICATION_ATTACH_COMPLETED("APPLICATION_ATTACH_COMPLETED"),
    APPLICATION_ATTACH_FAILED("APPLICATION_ATTACH_FAILED"),
    MISSING_UPLOADER_CONFIG("MISSING_UPLOADER_CONFIG"),
    CONTEXT_NOT_APPLICATION("CONTEXT_NOT_APPLICATION"),
    EVENT_PROVIDER_FAILED("EVENT_PROVIDER_FAILED"),
    ACTIVITY_OBSERVER_INSTALL_FAILED("ACTIVITY_OBSERVER_INSTALL_FAILED"),
    EVENT_INITIALIZATION_FAILED("EVENT_INITIALIZATION_FAILED"),
    EVENT_UPLOADER_INITIALIZATION_FAILED("EVENT_UPLOADER_INITIALIZATION_FAILED"),
    APPLICATION_ON_CREATE_ENTER("APPLICATION_ON_CREATE_ENTER"),
    APPLICATION_ON_CREATE_COMPLETED("APPLICATION_ON_CREATE_COMPLETED"),
    APPLICATION_ON_CREATE_FAILED("APPLICATION_ON_CREATE_FAILED"),
    TERMINAL_CONFLICT("TERMINAL_CONFLICT"),
    PERSISTENCE_DEGRADED("PERSISTENCE_DEGRADED"),
    RECOVERY("RECOVERY"),
    PREVIOUS_STARTUP_INCOMPLETE("PREVIOUS_STARTUP_INCOMPLETE"),
    JOURNAL_CORRUPTED("JOURNAL_CORRUPTED"),
    JOURNAL_TRUNCATED("JOURNAL_TRUNCATED"),
    JOURNAL_QUARANTINE_FAILED("JOURNAL_QUARANTINE_FAILED"),
    JOURNAL_DELETE_FAILED("JOURNAL_DELETE_FAILED"),
    LOCK_DELETE_FAILED("LOCK_DELETE_FAILED"),
    LOCK_PROBE_FAILED("LOCK_PROBE_FAILED"),
    TARGET_PAUSED("TARGET_PAUSED"),
    RETENTION_EVICTED("RETENTION_EVICTED"),
    CAPACITY_EVICTED("CAPACITY_EVICTED"),
    CORRUPT_FILE_EXPIRED("CORRUPT_FILE_EXPIRED"),
    CORRUPT_FILE_DELETE_FAILED("CORRUPT_FILE_DELETE_FAILED"),
    INVALID_PAYLOAD("INVALID_PAYLOAD"),
    UPLOADER_EXCEPTION("UPLOADER_EXCEPTION");
    private final String wireName;
    LocalStartupDiagnosticCode(String wireName) { this.wireName = wireName; }
    public String getWireName() { return wireName; }
    public static LocalStartupDiagnosticCode fromWireName(String name) {
        for (LocalStartupDiagnosticCode value : values()) if (value.wireName.equals(name)) return value;
        throw new IllegalArgumentException("Unknown LocalStartupDiagnosticCode: " + name);
    }
}

