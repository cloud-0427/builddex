package io.github.xjc.jiagu.local;

public enum LocalStartupResultCode {
    NONE(""),
    ACTIVITY_RESUMED("ACTIVITY_RESUMED"),
    APPLICATION_CREATED("APPLICATION_CREATED"),
    CLASSLOADER_CREATED("CLASSLOADER_CREATED"),
    DEX_VALIDATED("DEX_VALIDATED"),
    LOCAL_ALLOCATION_FAILED("LOCAL_ALLOCATION_FAILED"),
    LOCAL_APK_IDENTITY_CHANGED("LOCAL_APK_IDENTITY_CHANGED"),
    LOCAL_APPLICATION_CREATE_FAILED("LOCAL_APPLICATION_CREATE_FAILED"),
    LOCAL_BOOTSTRAP_FAILED("LOCAL_BOOTSTRAP_FAILED"),
    LOCAL_BOOTSTRAP_REENTRANT("LOCAL_BOOTSTRAP_REENTRANT"),
    LOCAL_CLASSLOADER_CREATE_FAILED("LOCAL_CLASSLOADER_CREATE_FAILED"),
    LOCAL_DEX_PARSE_FAILED("LOCAL_DEX_PARSE_FAILED"),
    LOCAL_PAYLOAD_AUTH_FAILED("LOCAL_PAYLOAD_AUTH_FAILED"),
    LOCAL_PAYLOAD_CONFIG_INVALID("LOCAL_PAYLOAD_CONFIG_INVALID"),
    LOCAL_PAYLOAD_DECRYPT_FAILED("LOCAL_PAYLOAD_DECRYPT_FAILED"),
    LOCAL_PAYLOAD_DEX_HEADER_INVALID("LOCAL_PAYLOAD_DEX_HEADER_INVALID"),
    LOCAL_PAYLOAD_DEX_TABLE_INVALID("LOCAL_PAYLOAD_DEX_TABLE_INVALID"),
    LOCAL_PAYLOAD_DUPLICATE("LOCAL_PAYLOAD_DUPLICATE"),
    LOCAL_PAYLOAD_FACTORY_UNSUPPORTED("LOCAL_PAYLOAD_FACTORY_UNSUPPORTED"),
    LOCAL_PAYLOAD_FORMAT_UNSUPPORTED("LOCAL_PAYLOAD_FORMAT_UNSUPPORTED"),
    LOCAL_PAYLOAD_HASH_MISMATCH("LOCAL_PAYLOAD_HASH_MISMATCH"),
    LOCAL_PAYLOAD_LENGTH_INVALID("LOCAL_PAYLOAD_LENGTH_INVALID"),
    LOCAL_PAYLOAD_MEMORY_BUDGET_EXCEEDED("LOCAL_PAYLOAD_MEMORY_BUDGET_EXCEEDED"),
    LOCAL_PAYLOAD_MISSING("LOCAL_PAYLOAD_MISSING"),
    LOCAL_PAYLOAD_PACKAGE_MISMATCH("LOCAL_PAYLOAD_PACKAGE_MISMATCH"),
    LOCAL_PAYLOAD_READ_FAILED("LOCAL_PAYLOAD_READ_FAILED"),
    LOCAL_PAYLOAD_VERSION_INVALID("LOCAL_PAYLOAD_VERSION_INVALID"),
    PAYLOAD_READ("PAYLOAD_READ"),
    PAYLOAD_VERIFIED("PAYLOAD_VERIFIED"),
    REPORTER_READY("REPORTER_READY");
    private final String wireName;
    LocalStartupResultCode(String wireName) { this.wireName = wireName; }
    public String getWireName() { return wireName; }
    public static LocalStartupResultCode fromWireName(String name) {
        for (LocalStartupResultCode value : values()) if (value.wireName.equals(name)) return value;
        throw new IllegalArgumentException("Unknown LocalStartupResultCode: " + name);
    }
}
